// Adds the AGPL header (.github/agpl_header.txt) to source files that lack it.
//
//   node scripts/license-header.mjs <files…>   add it (the pre-commit hook does this)
//   node scripts/license-header.mjs --check    list tracked files without it; exit 1 if any (CI)

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { extname } from "node:path";

const MARKER = "GNU Affero General Public License";
/** Generated by `wrangler types`; a header would be lost on every regeneration. */
const GENERATED = new Set(["worker-configuration.d.ts"]);

const header = readFileSync(new URL("../.github/agpl_header.txt", import.meta.url), "utf8").trimEnd().split("\n");

const STYLES = {
  block: (lines) => ["/*", ...lines.map((l) => (l ? ` * ${l}` : " *")), " */"].join("\n"),
  hash: (lines) => lines.map((l) => (l ? `# ${l}` : "#")).join("\n"),
};
const STYLE_BY_EXTENSION = {
  ".ts": STYLES.block,
  ".mts": STYLES.block,
  ".js": STYLES.block,
  ".mjs": STYLES.block,
  ".jsonc": STYLES.block,
  ".yml": STYLES.hash,
  ".yaml": STYLES.hash,
};

function applies(file) {
  return extname(file) in STYLE_BY_EXTENSION && !GENERATED.has(file.split("/").pop());
}

function hasHeader(text) {
  return text.split("\n").slice(0, 30).some((line) => line.includes(MARKER));
}

function addHeader(file) {
  const text = readFileSync(file, "utf8");
  if (hasHeader(text)) return false;
  const comment = STYLE_BY_EXTENSION[extname(file)](header);
  // Keep a shebang on the first line.
  const shebang = text.startsWith("#!") ? text.slice(0, text.indexOf("\n") + 1) : "";
  writeFileSync(file, `${shebang}${comment}\n\n${text.slice(shebang.length)}`);
  return true;
}

const args = process.argv.slice(2);
if (args[0] === "--check") {
  const tracked = execFileSync("git", ["ls-files"], { encoding: "utf8" }).split("\n").filter(Boolean);
  const missing = tracked.filter(applies).filter((file) => !hasHeader(readFileSync(file, "utf8")));
  for (const file of missing) console.error(`missing license header: ${file}`);
  if (missing.length) {
    console.error("Run `npm run license:fix` to add it.");
    process.exit(1);
  }
} else if (args[0] === "--fix") {
  const tracked = execFileSync("git", ["ls-files"], { encoding: "utf8" }).split("\n").filter(Boolean);
  for (const file of tracked.filter(applies)) if (addHeader(file)) console.log(`added license header: ${file}`);
} else {
  for (const file of args.filter(applies)) if (addHeader(file)) console.log(`added license header: ${file}`);
}
